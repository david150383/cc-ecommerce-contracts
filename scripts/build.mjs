// Generates asyncapi/asyncapi.json and docs/OWNERSHIP.md from the schemas (the single source).
//   node scripts/build.mjs           write them
//   node scripts/build.mjs --check   fail if the committed files are stale (CI)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadCatalog, loadOpenApi, ROOT } from "../lib/catalog.mjs";
import { API_CONSUMERS, SERVICES } from "../lib/services.mjs";

const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
const catalog = loadCatalog();
const check = process.argv.includes("--check");

// ------------------------------------------------------------------------------------- AsyncAPI
function asyncapi() {
  const channels = {};
  const operations = {};
  const messages = {};
  for (const m of catalog.messages) {
    const [transport, address] = m.channel.split(" ");
    const id = address.replace(/\.fifo$/, "");
    const key = `${m.name}V${m.version}`;
    messages[key] = {
      name: m.name,
      title: `${m.name} v${m.version}`,
      summary: m.schema.description ?? m.schema.title,
      contentType: "application/json",
      // JSON Schema 2020-12, not the AsyncAPI schema dialect: say so explicitly.
      payload: { schemaFormat: "application/schema+json;version=2020-12", schema: { $ref: `../${m.path}` } },
      "x-kind": m.kind,
      "x-owner": m.owner,
    };
    channels[id] ??= {
      address,
      title: id,
      description:
        transport === "SNS"
          ? `SNS topic. Fanned out to SQS inbox queues, filtered on the messageType attribute.`
          : `SQS queue: commands for exactly one consumer.${address.endsWith(".fifo") ? " FIFO, MessageGroupId = orderId." : ""}`,
      messages: {},
      // Names WITHOUT the environment prefix: Terraform creates "<env>-ecommerce-<name>".
      bindings:
        transport === "SNS"
          ? { sns: { name: address, bindingVersion: "0.1.0" } }
          : { sqs: { queue: { name: address, fifoQueue: address.endsWith(".fifo") }, bindingVersion: "0.2.0" } },
    };
    channels[id].messages[key] = { $ref: `#/components/messages/${key}` };
    for (const p of m.producers) {
      operations[`${p}.send.${key}`] = { action: "send", channel: { $ref: `#/channels/${id}` }, messages: [{ $ref: `#/channels/${id}/messages/${key}` }], "x-service": p };
    }
    for (const c of m.consumers) {
      operations[`${c}.receive.${key}`] = { action: "receive", channel: { $ref: `#/channels/${id}` }, messages: [{ $ref: `#/channels/${id}/messages/${key}` }], "x-service": c };
    }
  }
  const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
  return {
    asyncapi: "3.0.0",
    info: {
      title: "E-commerce platform messaging",
      version: pkg.version,
      description: "Events (owned by their producer, SNS) and commands (owned by their consumer, SQS). Generated from schemas/ by scripts/build.mjs.",
    },
    defaultContentType: "application/json",
    channels: sorted(channels),
    operations: sorted(operations),
    components: { messages: sorted(messages) },
  };
}

// ------------------------------------------------------------------------------- ownership matrix
function ownership() {
  const rows = catalog.messages.map(
    (m) => `| \`${m.name}\` v${m.version} | ${m.kind} | **${m.owner}** | ${m.producers.join(", ")} | ${m.consumers.join(", ") || "—"} | ${m.channel} | [schema](../${m.path}) |`,
  );
  const openapi = loadOpenApi();
  const apis = SERVICES.map((s) => {
    const doc = openapi[s.name];
    const ops = doc ? Object.values(doc.paths).reduce((n, p) => n + Object.keys(p).filter((k) => ["get", "post", "put", "patch", "delete"].includes(k)).length, 0) : 0;
    return `| **${s.name}** | ${doc ? `[OpenAPI ${doc.openapi}](../openapi/${s.name}.openapi.json)` : "—"} | ${ops} | ${(API_CONSUMERS[s.name] ?? []).join(", ")} |`;
  });
  return `<!-- Generated by scripts/build.mjs from schemas/, openapi/ and lib/services.mjs. Do not edit. -->
# Ownership matrix

Rules: an **event** is owned by its producer; a **command** is owned by its consumer (it is part of the
receiver's API). The owner decides changes, under [VERSIONING.md](../VERSIONING.md); everyone listed is
affected by them.

## Messages (${catalog.messages.length})

| Message | Kind | Owner | Producers | Consumers | Channel | Schema |
|---|---|---|---|---|---|---|
${rows.join("\n")}

All messages share [the envelope](../schemas/common/envelope.v1.schema.json) (owned by the platform: a change
to it is a change to every message).

## HTTP APIs

| Owner | Contract | Operations | Clients |
|---|---|---|---|
${apis.join("\n")}
`;
}

// ------------------------------------------------------------------------------------------ write
const outputs = {
  "asyncapi/asyncapi.json": `${JSON.stringify(asyncapi(), null, 2)}\n`,
  "docs/OWNERSHIP.md": ownership(),
};
let stale = 0;
for (const [rel, content] of Object.entries(outputs)) {
  const path = join(ROOT, rel);
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    // not generated yet
  }
  if (current === content) continue;
  if (check) {
    console.error(`${rel} is stale: run npm run build`);
    stale++;
  } else {
    mkdirSync(join(path, ".."), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${rel}`);
  }
}
if (stale) process.exit(1);
